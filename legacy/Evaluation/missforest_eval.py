def missforest_eval(
    fractions,
    missingness_types,
    columns_num: str = "all",
    study_name: str = "MissForest_balanced_MAR_MNAR_10_30_seeded_v1",
    seeds: Sequence[int] = (42, 100, 2024, 777, 999),
    output_dir: Optional[str] = None,
    show: bool = True,
    strict: bool = True,
    require_condition_scores: bool = True,
) -> Dict[str, Any]:
    """
    Evaluate the seeded MissForest pipeline.

    Directory behavior
    ------------------
    The canonical CSV outputs are always written to:

        <experiments_dir>/Evaluation/MissForest_seeded_pipeline/

    This is the location expected by the cross-method seeded comparison
    evaluator. If ``output_dir`` is supplied, it is used only for plots and the
    PDF report. This allows a separate main-figure folder without moving the
    canonical RMSE tables.
    """

    fractions = [float(x) for x in fractions]
    missingness_types = [str(x).upper() for x in missingness_types]
    seeds = [int(x) for x in seeds]

    base_dir = Path(config_paths.experiments_dir(columns_num))

    # Canonical machine-readable outputs. The cross-method evaluator expects
    # MissForest_final_rmse_by_seed.csv here.
    canonical_dir = base_dir / "Evaluation" / "MissForest_seeded_pipeline"
    canonical_dir.mkdir(parents=True, exist_ok=True)

    # Optional separate directory for figures, for example a main-figure-only
    # run using fractions [0.1, 0.3, 0.5].
    if output_dir is None:
        plot_dir = canonical_dir
    else:
        plot_dir = Path(output_dir).expanduser().resolve()
        plot_dir.mkdir(parents=True, exist_ok=True)

    best_params, best_params_path, best_payload = _load_best_params(
        base_dir,
        study_name,
    )

    print("\n" + "=" * 80)
    print("MissForest evaluation suite")
    print("=" * 80)
    print(f"Study name: {study_name}")
    print(f"Best params JSON: {best_params_path}")
    print(f"Best params: {best_params}")
    print(f"Fractions: {fractions}")
    print(f"Missingness types: {missingness_types}")
    print(f"Seeds: {seeds}")
    print(f"Canonical CSV directory: {canonical_dir}")
    print(f"Plot/report directory: {plot_dir}")
    print("=" * 80)

    tuning_df = _load_mf_condition_scores(
        base_dir=base_dir,
        study_name=study_name,
        require_condition_scores=require_condition_scores,
    )

    # Always save canonical tables in the directory expected by the combined
    # method comparison evaluator.
    tuning_csv = (
        canonical_dir
        / "MissForest_optuna_per_condition_validation_rmse.csv"
    )
    tuning_df.to_csv(tuning_csv, index=False)
    print(f"\nSaved Optuna per-condition values: {tuning_csv}")

    seed_df = _load_mf_seed_rmse_values(
        base_dir=base_dir,
        columns_num=columns_num,
        fractions=fractions,
        missingness_types=missingness_types,
        seeds=seeds,
        best_params=best_params,
        strict=strict,
    )

    seed_csv = canonical_dir / "MissForest_final_rmse_by_seed.csv"
    seed_df.to_csv(seed_csv, index=False)
    print(f"Saved final seed RMSE values: {seed_csv}")

    seed_summary = (
        seed_df.groupby(["missingness", "fraction"], as_index=False)["rmse"]
        .agg(["count", "mean", "std", "median", "min", "max"])
        .reset_index()
    )

    seed_summary_csv = (
        canonical_dir
        / "MissForest_final_rmse_by_seed_summary.csv"
    )
    seed_summary.to_csv(seed_summary_csv, index=False)
    print(f"Saved final seed RMSE summary: {seed_summary_csv}")

    output_paths: Dict[str, Any] = {
        "best_params": best_params,
        "best_params_path": str(best_params_path),
        "canonical_data_dir": str(canonical_dir),
        "plot_output_dir": str(plot_dir),
        "tuning_csv": str(tuning_csv),
        "seed_csv": str(seed_csv),
        "seed_summary_csv": str(seed_summary_csv),
        "plots": {},
    }

    output_paths["plots"]["hyperparameter_effect"] = (
        plot_mf_hyperparameter_effect(
            tuning_df,
            best_params=best_params,
            out_dir=plot_dir,
            study_name=study_name,
            show=show,
        )
    )

    output_paths["plots"]["hyperparameter_search_distribution"] = (
        plot_mf_hyperparameter_search_distribution(
            tuning_df,
            best_params=best_params,
            out_dir=plot_dir,
            study_name=study_name,
            show=show,
        )
    )

    output_paths["plots"]["seed_ribbon"] = plot_mf_seed_ribbon(
        seed_df,
        best_params=best_params,
        out_dir=plot_dir,
        show=show,
    )

    output_paths["plots"]["seed_boxplots"] = plot_mf_seed_boxplots(
        seed_df,
        best_params=best_params,
        out_dir=plot_dir,
        show=show,
    )

    report_pdf = plot_dir / "MissForest_evaluation_suite_report.pdf"

    with PdfPages(report_pdf) as pdf:
        fig, ax = plt.subplots(figsize=(8.5, 11))
        ax.axis("off")

        lines = [
            "MissForest evaluation suite",
            "",
            f"Study name: {study_name}",
            f"Best params: {best_params}",
            "",
            f"Canonical CSV directory: {canonical_dir}",
            f"Plot/report directory: {plot_dir}",
            "",
            "Generated plots:",
            f"1. {output_paths['plots']['hyperparameter_effect']['pdf']}",
            f"2. {output_paths['plots']['hyperparameter_search_distribution']['pdf']}",
            f"3. {output_paths['plots']['seed_ribbon']['pdf']}",
            f"4. {output_paths['plots']['seed_boxplots']['pdf']}",
            "",
            "Canonical CSV outputs:",
            f"- {tuning_csv}",
            f"- {seed_csv}",
            f"- {seed_summary_csv}",
        ]

        y = 0.95

        for i, line in enumerate(lines):
            ax.text(
                0.05,
                y,
                line,
                fontsize=16 if i == 0 else 10,
                fontweight="bold" if i == 0 else "normal",
                ha="left",
                va="top",
                transform=ax.transAxes,
            )
            y -= 0.04 if i == 0 else 0.028

        pdf.savefig(fig, bbox_inches="tight")
        plt.close(fig)

    output_paths["combined_report_pdf"] = str(report_pdf)

    print("\n" + "=" * 80)
    print("MissForest evaluation complete")
    print("=" * 80)
    print(f"Canonical repeated-seed CSV: {seed_csv}")
    print(f"Combined output summary PDF: {report_pdf}")
    print("Publication-quality individual plots:")
    for key, value in output_paths["plots"].items():
        print(f"  {key}: {value['pdf']}")
    print("=" * 80)

    return output_paths

