def _ordered_missingness(values: Sequence[str]) -> List[str]:
    preferred = ["MCAR", "MAR", "MNAR"]
    values = [str(v).upper() for v in values]
    present = [m for m in preferred if m in set(values)]
    extras = sorted([m for m in set(values) if m not in present])
    return present + extras


def _read_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"Required JSON file not found:\n{path}")

    with open(path, "r") as f:
        return json.load(f)


def _sf_token(sample_fraction) -> str:
    return str(sample_fraction)


def _parse_json_or_literal(raw: Any) -> Dict[str, Any]:
    if raw is None:
        return {}

    if isinstance(raw, dict):
        return raw

    if pd.isna(raw):
        return {}

    s = str(raw).strip()

    if not s or s.lower() in {"none", "nan", "null"}:
        return {}

    try:
        parsed = json.loads(s)
        if isinstance(parsed, dict):
            return parsed
    except Exception:
        pass

    try:
        parsed = ast.literal_eval(s)
        if isinstance(parsed, dict):
            return parsed
    except Exception:
        pass

    return {}


def _load_best_params(base_dir: Path, study_name: str) -> Tuple[Dict[str, Any], Path, Dict[str, Any]]:
    best_params_path = base_dir / "Optimization" / "best_params" / f"{study_name}_best_params.json"
    payload = _read_json(best_params_path)

    params = payload.get("params", {})

    required = {"niter", "ntree", "max_depth", "sample_fraction"}
    missing = required - set(params.keys())

    if missing:
        raise KeyError(
            f"Best params JSON exists but is missing required params: {sorted(missing)}\n"
            f"File: {best_params_path}\n"
            f"params: {params}"
        )

    params = {
        "niter": int(params["niter"]),
        "ntree": int(params["ntree"]),
        "max_depth": int(params["max_depth"]),
        "sample_fraction": float(params["sample_fraction"]),
    }

    return params, best_params_path, payload


def _load_mf_condition_scores(
    *,
    base_dir: Path,
    study_name: str,
    require_condition_scores: bool = True,
) -> pd.DataFrame:
    """
    Read per-condition validation RMSE generated by updated run_bayes_opt.py.

    Required file:
        Optimization/trial_tables/<study_name>_condition_scores.csv
    """
    condition_csv = base_dir / "Optimization" / "trial_tables" / f"{study_name}_condition_scores.csv"

    if not condition_csv.exists():
        raise FileNotFoundError(
            f"Per-condition Optuna score table not found:\n{condition_csv}\n\n"
            "This means MissForest optimization was not run with the updated run_bayes_opt.py "
            "that writes condition_scores_csv_path. Rerun optimization with a new study name."
        )

    df = pd.read_csv(condition_csv)

    if df.empty and require_condition_scores:
        raise RuntimeError(
            f"Condition score table exists but is empty:\n{condition_csv}\n\n"
            "Rerun MissForest optimization with the updated run_bayes_opt.py."
        )

    required = {"trial_number", "state", "fraction", "missingness", "validation_rmse"}

    missing = required - set(df.columns)

    if missing:
        raise KeyError(
            f"Condition score table is missing required columns {sorted(missing)}.\n"
            f"File: {condition_csv}\n"
            f"Columns: {list(df.columns)}"
        )

    df = df[df["state"].astype(str).str.upper() == "COMPLETE"].copy()

    if df.empty and require_condition_scores:
        raise RuntimeError(
            f"No COMPLETE rows found in condition score table:\n{condition_csv}"
        )

    # Try explicit params columns first.
    param_map = {
        "niter": ["params_niter", "method_params_niter", "niter"],
        "ntree": ["params_ntree", "method_params_ntree", "ntree"],
        "max_depth": ["params_max_depth", "method_params_max_depth", "max_depth"],
        "sample_fraction": ["params_sample_fraction", "method_params_sample_fraction", "sample_fraction"],
    }

    for param_name, candidates in param_map.items():
        if param_name not in df.columns:
            found = None
            for c in candidates:
                if c in df.columns:
                    found = c
                    break

            if found is not None:
                df[param_name] = df[found]

    # Fall back to method_params_json if needed.
    if not all(c in df.columns for c in ["niter", "ntree", "max_depth", "sample_fraction"]):
        if "method_params_json" not in df.columns:
            raise KeyError(
                "Could not find MissForest parameter columns and method_params_json is missing."
            )

        parsed_params = df["method_params_json"].map(_parse_json_or_literal)

        for param_name in ["niter", "ntree", "max_depth", "sample_fraction"]:
            if param_name not in df.columns:
                df[param_name] = parsed_params.map(lambda d: d.get(param_name, np.nan))

    required_params = ["niter", "ntree", "max_depth", "sample_fraction"]

    for col in required_params:
        if df[col].isna().any():
            bad = df[df[col].isna()].head()
            raise ValueError(
                f"Column {col} has missing values in condition score table.\n"
                f"Bad rows:\n{bad.to_string(index=False)}"
            )

    df["trial_number"] = pd.to_numeric(df["trial_number"], errors="raise").astype(int)
    df["fraction"] = pd.to_numeric(df["fraction"], errors="raise")
    df["missingness"] = df["missingness"].astype(str).str.upper()
    df["validation_rmse"] = pd.to_numeric(df["validation_rmse"], errors="raise")

    df["niter"] = pd.to_numeric(df["niter"], errors="raise").astype(int)
    df["ntree"] = pd.to_numeric(df["ntree"], errors="raise").astype(int)
    df["max_depth"] = pd.to_numeric(df["max_depth"], errors="raise").astype(int)
    df["sample_fraction"] = pd.to_numeric(df["sample_fraction"], errors="raise")

    df["config_label"] = df.apply(
        lambda r: (
            f"ntree={int(r['ntree'])}, "
            f"niter={int(r['niter'])}, "
            f"depth={int(r['max_depth'])}, "
            f"sf={float(r['sample_fraction']):g}"
        ),
        axis=1,
    )

    df = df.sort_values(
        ["missingness", "fraction", "trial_number"]
    ).reset_index(drop=True)

    return df


def _load_mf_seed_rmse_values(
    *,
    base_dir: Path,
    columns_num: str,
    fractions: Sequence[float],
    missingness_types: Sequence[str],
    seeds: Sequence[int],
    best_params: Dict[str, Any],
    strict: bool = True,
) -> pd.DataFrame:
    rows = []
    missing_files = []

    ntree = int(best_params["ntree"])
    niter = int(best_params["niter"])
    max_depth = int(best_params["max_depth"])
    sample_fraction = float(best_params["sample_fraction"])
    sf = _sf_token(sample_fraction)

    for missingness in missingness_types:
        missingness = str(missingness).upper()

        for fraction in fractions:
            fraction = float(fraction)
            folder = base_dir / f"fraction_{fraction}_missingness_{missingness}"

            for seed in seeds:
                seed = int(seed)

                rmse_path = (
                    folder
                    / f"RMSE_mf_col_{columns_num}_nt_{ntree}_niter_{niter}_md_{max_depth}_sf_{sf}_seed_{seed}.csv"
                )

                imputed_path = (
                    folder
                    / f"imputed_mf_col_{columns_num}_nt_{ntree}_niter_{niter}_md_{max_depth}_sf_{sf}_seed_{seed}.csv"
                )

                if not rmse_path.exists():
                    missing_files.append(str(rmse_path))
                    continue

                if strict and not imputed_path.exists():
                    missing_files.append(str(imputed_path))
                    continue

                try:
                    rmse_df = pd.read_csv(rmse_path)
                    rmse = float(pd.to_numeric(rmse_df.iloc[:, 0], errors="coerce").dropna().iloc[0])
                except Exception as e:
                    raise ValueError(
                        f"Could not read RMSE from:\n{rmse_path}\nError: {e}"
                    )

                rows.append(
                    {
                        "method": "mf",
                        "ntree": ntree,
                        "niter": niter,
                        "max_depth": max_depth,
                        "sample_fraction": sample_fraction,
                        "missingness": missingness,
                        "fraction": fraction,
                        "seed": seed,
                        "rmse": rmse,
                        "rmse_path": str(rmse_path),
                        "imputed_path": str(imputed_path),
                    }
                )

    if missing_files and strict:
        preview = "\n".join(missing_files[:40])
        raise FileNotFoundError(
            "Some required repeated-seed final MissForest benchmark files are missing.\n\n"
            f"First missing files:\n{preview}\n\n"
            "Run the MissForest repeated final benchmark for all requested seeds, "
            "fractions, and missingness types."
        )

    df = pd.DataFrame(rows)

    if df.empty:
        raise RuntimeError(
            "No MissForest repeated-seed RMSE files were found."
        )

    return df.sort_values(["missingness", "fraction", "seed"]).reset_index(drop=True)


def _save_current_figure(fig, out_dir: Path, stem: str, show: bool) -> Dict[str, str]:
    out_dir.mkdir(parents=True, exist_ok=True)

    png = out_dir / f"{stem}.png"
    pdf = out_dir / f"{stem}.pdf"

    fig.savefig(png, dpi=300, bbox_inches="tight")
    fig.savefig(pdf, bbox_inches="tight")

    if show:
        plt.show()

    plt.close(fig)

    return {
        "png": str(png),
        "pdf": str(pdf),
    }


