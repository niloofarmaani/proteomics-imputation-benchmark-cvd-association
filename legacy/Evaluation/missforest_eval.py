def plot_mf_hyperparameter_effect(
    tuning_df: pd.DataFrame,
    *,
    best_params: Dict[str, Any],
    out_dir: Path,
    study_name: str,
    show: bool = True,
) -> Dict[str, str]:
    """
    Fixed optimization seed, changing MissForest hyperparameters.

    One panel per missingness type.
    x-axis = missing fraction.
    y-axis = validation RMSE.
    gray lines = trial hyperparameter configurations.
    black line = mean across trial configurations.
    red line = selected best configuration.
    gray ribbon = min to max across trial configurations.
    """
    df = tuning_df.copy()

    missingness_types = _ordered_missingness(df["missingness"].unique())

    best_label = (
        f"ntree={int(best_params['ntree'])}, "
        f"niter={int(best_params['niter'])}, "
        f"depth={int(best_params['max_depth'])}, "
        f"sf={float(best_params['sample_fraction']):g}"
    )

    fig, axes = plt.subplots(
        1,
        len(missingness_types),
        figsize=(6.2 * len(missingness_types), 4.8),
        sharey=True,
    )

    if len(missingness_types) == 1:
        axes = [axes]

    for ax, missingness in zip(axes, missingness_types):
        sub = df[df["missingness"] == missingness].copy()

        by_config = (
            sub.groupby(["config_label", "fraction"], as_index=False)["validation_rmse"]
            .mean()
            .sort_values(["config_label", "fraction"])
        )

        band = (
            by_config.groupby("fraction")["validation_rmse"]
            .agg(["min", "max", "mean"])
            .reset_index()
            .sort_values("fraction")
        )

        x_band = band["fraction"].to_numpy(dtype=float)

        ax.fill_between(
            x_band,
            band["min"].to_numpy(dtype=float),
            band["max"].to_numpy(dtype=float),
            color="gray",
            alpha=0.15,
            label="range across configs",
        )

        ax.plot(
            x_band,
            band["mean"].to_numpy(dtype=float),
            color="black",
            linestyle="--",
            linewidth=2.0,
            label="mean across configs",
        )

        for config_label, g in by_config.groupby("config_label"):
            g = g.sort_values("fraction")

            is_best = config_label == best_label

            ax.plot(
                g["fraction"],
                g["validation_rmse"],
                color="tab:red" if is_best else "gray",
                alpha=1.0 if is_best else 0.25,
                linewidth=3.0 if is_best else 1.0,
                marker="o" if is_best else ".",
                label="selected best config" if is_best else None,
            )

        ax.set_title(missingness)
        ax.set_xlabel("Missing fraction")
        ax.grid(True, alpha=0.30)

    axes[0].set_ylabel("Validation RMSE")

    handles, labels = axes[-1].get_legend_handles_labels()

    fig.legend(
        handles,
        labels,
        loc="center left",
        bbox_to_anchor=(1.02, 0.5),
    )

    fig.suptitle(
        f"MissForest hyperparameter effect under fixed optimization seed\nStudy: {study_name}",
        y=1.04,
    )

    fig.tight_layout(rect=[0, 0, 0.84, 1])

    return _save_current_figure(
        fig,
        out_dir,
        "MissForest_hyperparameter_effect_fixed_seed",
        show,
    )


def plot_mf_hyperparameter_search_distribution(
    tuning_df: pd.DataFrame,
    *,
    best_params: Dict[str, Any],
    out_dir: Path,
    study_name: str,
    show: bool = True,
) -> Dict[str, str]:
    """
    Show how each MissForest hyperparameter relates to validation RMSE.
    """
    df = tuning_df.copy()

    params = [
        ("ntree", int(best_params["ntree"])),
        ("niter", int(best_params["niter"])),
        ("max_depth", int(best_params["max_depth"])),
        ("sample_fraction", float(best_params["sample_fraction"])),
    ]

    fig, axes = plt.subplots(1, 4, figsize=(18, 4.8), sharey=True)

    for ax, (param, best_value) in zip(axes, params):
        values = sorted(df[param].dropna().unique())

        data = [
            df.loc[df[param] == value, "validation_rmse"].to_numpy(dtype=float)
            for value in values
        ]

        bp = ax.boxplot(
            data,
            labels=[f"{v:g}" if isinstance(v, float) else str(v) for v in values],
            patch_artist=True,
            showmeans=True,
            meanprops={
                "marker": "D",
                "markerfacecolor": "white",
                "markeredgecolor": "black",
            },
        )

        for patch, value in zip(bp["boxes"], values):
            if float(value) == float(best_value):
                patch.set_facecolor("tab:red")
                patch.set_alpha(0.45)
            else:
                patch.set_facecolor("tab:blue")
                patch.set_alpha(0.25)

        ax.set_title(param)
        ax.set_xlabel(param)
        ax.grid(True, axis="y", alpha=0.30)

    axes[0].set_ylabel("Validation RMSE")

    fig.suptitle(
        f"MissForest hyperparameter search distributions\nStudy: {study_name}",
        y=1.04,
    )

    fig.tight_layout()

    return _save_current_figure(
        fig,
        out_dir,
        "MissForest_hyperparameter_search_distribution",
        show,
    )


def plot_mf_seed_ribbon(
    seed_df: pd.DataFrame,
    *,
    best_params: Dict[str, Any],
    out_dir: Path,
    show: bool = True,
) -> Dict[str, str]:
    df = seed_df.copy()
    df["missingness"] = df["missingness"].astype(str).str.upper()
    df["fraction"] = pd.to_numeric(df["fraction"], errors="raise")
    df["seed"] = pd.to_numeric(df["seed"], errors="raise").astype(int)
    df["rmse"] = pd.to_numeric(df["rmse"], errors="raise")

    missingness_types = _ordered_missingness(df["missingness"].unique())

    fig, axes = plt.subplots(
        1,
        len(missingness_types),
        figsize=(6.2 * len(missingness_types), 4.8),
        sharey=True,
    )

    if len(missingness_types) == 1:
        axes = [axes]

    for ax, missingness in zip(axes, missingness_types):
        sub = df[df["missingness"] == missingness].copy()

        for seed, g in sub.groupby("seed"):
            g = g.sort_values("fraction")

            ax.plot(
                g["fraction"],
                g["rmse"],
                color="gray",
                alpha=0.35,
                linewidth=1.0,
                marker=".",
            )

        summary = (
            sub.groupby("fraction")["rmse"]
            .agg(["mean", "std"])
            .reset_index()
            .sort_values("fraction")
        )

        x = summary["fraction"].to_numpy(dtype=float)
        mean = summary["mean"].to_numpy(dtype=float)
        std = summary["std"].fillna(0.0).to_numpy(dtype=float)

        ax.fill_between(
            x,
            mean - std,
            mean + std,
            color="black",
            alpha=0.15,
            label="mean ± 1 SD",
        )

        ax.plot(
            x,
            mean,
            color="black",
            linewidth=2.5,
            marker="o",
            label="mean",
        )

        ax.set_title(missingness)
        ax.set_xlabel("Missing fraction")
        ax.grid(True, alpha=0.30)

    axes[0].set_ylabel("Final RMSE")

    handles, labels = axes[-1].get_legend_handles_labels()

    if handles:
        fig.legend(
            handles,
            labels,
            loc="center left",
            bbox_to_anchor=(1.02, 0.5),
        )

    fig.suptitle(
        "MissForest seed robustness with frozen best hyperparameters\n"
        f"ntree={best_params['ntree']}, niter={best_params['niter']}, "
        f"depth={best_params['max_depth']}, sf={best_params['sample_fraction']:g}",
        y=1.04,
    )

    fig.tight_layout(rect=[0, 0, 0.88, 1])

    return _save_current_figure(
        fig,
        out_dir,
        "MissForest_seed_effect_fixed_best_params_ribbon",
        show,
    )


